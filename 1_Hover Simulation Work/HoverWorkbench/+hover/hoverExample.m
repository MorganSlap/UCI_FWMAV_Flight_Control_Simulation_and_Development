function settings = hoverExample(kind)
%HOVEREXAMPLE Reproducible IMU-only, trimmed-throttle flight examples.
% No altitude, position or heading measurement is supplied to the firmware.
% The throttle was measured against the pinned firmware and stock plant;
% re-trim it after changing mass, thrust coefficients or firmware endpoints.
arguments
    kind (1,1) string {mustBeMember(kind,["level","recovery"])} = "level"
end
settings=hover.defaultSettings();
settings.t_sim=10;
settings.sim_fidelity='high';
settings.noise_true=true;
settings.X0=zeros(12,1);
settings.Xref=zeros(12,1);
settings.FirmwareAdapter=struct('ThrottlePWM',1859,'NavigationSensors',0,'UseKnownAccelCalibration',true, ...
    'CommandMode','angle','SpoolupSeconds',1);
schema=bf.parseCliSettings(settings.Betaflight.SchemaText);
% Original torque-based PI gains, rounded to native integer menu values.
% For this plant and PWM endpoints: roll [132.9369 3.9598 0],
% pitch [133.6221 3.9802 0]. Reconvert if actuator scaling changes.
% Disable optional PID shaping through supported firmware settings. Keep
% the base configuration's 5 Hz filters, integral/output clamps and unselected
% mode defaults. The native accel cutoff rejects the 24 Hz wing vibration. The old
% accel.LPF_set field belongs to the replaced estimator and is inactive here.
values={ ...
    'imu_dcm_kp','2500'; 'imu_dcm_ki','0'; ...
    'gyro_calib_duration','400'; 'gyro_calib_noise_limit','200'; 'simplified_pids_mode','OFF'; ...
    'p_roll','133'; 'i_roll','4'; 'd_roll','0'; 'f_roll','0'; ...
    'p_pitch','134'; 'i_pitch','4'; 'd_pitch','0'; 'f_pitch','0'; ...
    'iterm_relax','OFF'; 'iterm_rotation','OFF'; ...
    'anti_gravity_gain','0'; 'anti_gravity_p_gain','0'; ...
    'd_max_roll','0'; 'd_max_pitch','0'; 'd_max_yaw','0'; ...
    'd_max_gain','0'; 'd_max_advance','0'; ...
    'tpa_rate','0'; 'tpa_low_rate','0'; ...
    'angle_feedforward','0'; 'angle_earth_ref','0'; ...
    'feedforward_averaging','OFF'; 'feedforward_smooth_factor','0'; ...
    'feedforward_jitter_factor','0'; 'feedforward_boost','0'; ...
    'feedforward_max_rate_limit','0'; 'feedforward_yaw_hold_gain','0'; ...
    'throttle_boost','0'; 'thrust_linear','0'; 'vbat_sag_compensation','0'; ...
    'acc_limit','0'; 'acc_limit_yaw','0'; ...
    'crash_recovery','OFF'; 'yaw_spin_recovery','OFF'};
for k=1:size(values,1)
    item=schema(strcmp({schema.Name},values{k,1}));
    if isempty(item), error('bf:PresetSchema','Missing firmware setting %s.',values{k,1}); end
    settings.Betaflight=bf.setSetting(settings.Betaflight,item(1),values{k,2},0);
end
settings.Betaflight.CLI=strrep(settings.Betaflight.CLI, ...
    'feature ANTI_GRAVITY','feature -ANTI_GRAVITY');
if kind=="recovery"
    settings.X0(7:8)=[5;-3]*pi/180;
end
end
