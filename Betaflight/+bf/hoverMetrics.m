function metrics=hoverMetrics(output)
%HOVERMETRICS Assess attitude, estimator error, translation and motor output.
t=output.state_output.time;
x=output.state_output.signals.values;
td=output.betaflight_diagnostics.time;
d=squeeze(output.betaflight_diagnostics.signals.values)';
truth=interp1(t,x(:,7:9),td);
error=atan2(sin(d(:,10:12)-truth),cos(d(:,10:12)-truth));
verticalSpeed=-sin(x(:,8)).*x(:,4)+sin(x(:,7)).*cos(x(:,8)).*x(:,5) ...
    +cos(x(:,7)).*cos(x(:,8)).*x(:,6);
outside=find(any(abs(x(:,7:8))>0.5*pi/180,2),1,'last');
settled=0;
if ~isempty(outside)
    if outside==numel(t), settled=NaN; else, settled=t(outside+1); end
end
metrics=struct('SimulatedSeconds',t(end),'AllFinite',all(isfinite(x),'all') && all(isfinite(d),'all'), ...
    'ArmedThroughout',all(d(:,31)==1),'AngleModeThroughout',all(bitand(uint32(d(:,33)),uint32(1))~=0), ...
    'FinalEulerDegrees',x(end,7:9)*180/pi,'PeakEulerDegrees',max(abs(x(:,7:9)))*180/pi, ...
    'EstimatorRmsDegrees',sqrt(mean(error.^2))*180/pi, ...
    'FinalNEDMetres',x(end,1:3),'AltitudeChangeMetres',x(1,3)-x(end,3), ...
    'PeakHorizontalDisplacementMetres',max(vecnorm(x(:,1:2)-x(1,1:2),2,2)), ...
    'FinalDownSpeedMetresPerSecond',verticalSpeed(end), ...
    'PeakDownSpeedMetresPerSecond',max(abs(verticalSpeed)), ...
    'AttitudeSettledWithinHalfDegreeSeconds',settled, ...
    'FinalMeanMotorCommand',mean(d(end,6:9)), ...
    'MotorCommandRange',[min(d(:,6:9),[],'all') max(d(:,6:9),[],'all')], ...
    'GyroPeriodMicroseconds',unique(d(:,34))','PidPeriodMicroseconds',unique(d(:,35))');
outside=find(any(abs(x(:,7:8))>pi/180,2),1,'last');
metrics.AttitudeSettledWithinOneDegreeSeconds=0;
if ~isempty(outside)
    if outside==numel(t), metrics.AttitudeSettledWithinOneDegreeSeconds=NaN;
    else, metrics.AttitudeSettledWithinOneDegreeSeconds=t(outside+1); end
end
end
