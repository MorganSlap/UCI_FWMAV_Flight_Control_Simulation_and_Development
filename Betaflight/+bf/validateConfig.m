function validateConfig(config)
%VALIDATECONFIG Validate configuration shape without executing its contents.
if ~isstruct(config) || ~isscalar(config) || ...
        ~all(isfield(config,{'Format','SchemaVersion','CLI','SchemaText','Firmware'})) || ...
        ~strcmp(string(config.Format),'BetaflightSimulationConfig') || ...
        ~isequal(config.SchemaVersion,1)
    error('bf:InvalidConfig','Expected a supported Betaflight simulation configuration.');
end
if ~((ischar(config.CLI) && (isrow(config.CLI) || isempty(config.CLI))) || ...
        (isstring(config.CLI) && isscalar(config.CLI))) || ...
        ~((ischar(config.SchemaText) && (isrow(config.SchemaText) || isempty(config.SchemaText))) || ...
        (isstring(config.SchemaText) && isscalar(config.SchemaText))) || ...
        ~isstruct(config.Firmware) || ~isscalar(config.Firmware)
    error('bf:InvalidConfig','CLI and SchemaText must be text; Firmware must be a scalar structure.');
end
end
