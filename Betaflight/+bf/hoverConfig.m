function config=hoverConfig(maxPot)
%HOVERCONFIG Betaflight configuration for the front/right/rear/left flappers.
% All flight algorithms remain the compiled upstream implementation. This
% preset selects native ANGLE mode and a custom mixer for the existing plant.
arguments
    maxPot (1,1) double {mustBeInRange(maxPot,1100,2000)} = 1950
end
config=bf.defaultConfig();
schema=bf.parseCliSettings(config.SchemaText);
values={ ...
    'acc_calibration','0,0,0,1'; 'mag_hardware','NONE'; 'baro_hardware','NONE'; ...
    'pid_process_denom','1'; 'motor_pwm_protocol','PWM'; ...
    'max_throttle',sprintf('%g',maxPot); 'motor_idle','550'; ...
    'simplified_pids_mode','OFF'; 'p_roll','10'; 'i_roll','0'; 'd_roll','0'; ...
    'f_roll','0'; 'p_pitch','10'; 'i_pitch','0'; 'd_pitch','0'; 'f_pitch','0'; ...
    'p_yaw','0'; 'i_yaw','0'; 'd_yaw','0'; 'f_yaw','0'; ...
    'angle_p_gain','20'; 'angle_limit','60'; 'thr_expo','0'; ...
    'throttle_boost','0'; 'thrust_linear','0'; 'anti_gravity_gain','0'};
for k=1:size(values,1)
    item=schema(strcmp({schema.Name},values{k,1}));
    if isempty(item), error('bf:PresetSchema','Missing firmware setting %s.',values{k,1}); end
    config=bf.setSetting(config,item(1),values{k,2},0);
end
[~,config]=bf.commandSection(config,{'mixer','mmix'},sprintf([ ...
    'mixer CUSTOM\nmmix reset\nmmix 0 1 0 1 -1\n' ...
    'mmix 1 1 -1 0 1\nmmix 2 1 0 -1 -1\nmmix 3 1 1 0 1']));
[~,config]=bf.commandSection(config,{'aux'},sprintf( ...
    'aux 0 0 0 1700 2100 0 0\naux 1 1 1 1700 2100 0 0'));
% Navigation hardware has no measurements in the existing hover simulation.
config.CLI=strrep(config.CLI,'feature GPS','feature -GPS');
end
