function pages = settingsPages()
%SETTINGSPAGES Presentation groups; every editable input appears once.
% Row heights keep related controls together in compact, two-column cards.
pages = struct('Name',{},'Description',{},'Heights',{},'Cards',{});
add('PID tuning','Rate-loop gains by axis. Values use the units and scaling in lin_hover.m.', ...
    {244,132}, [ ...
    card('RATE CONTROLLER',{'roll_P','roll_I','roll_D','pitch_P','pitch_I','pitch_D','yaw_P','yaw_I','yaw_D'},1,[1 2],'pid'), ...
    card('ANGLE MODE',{'strength'},2,[1 2])]);
add('Filters & estimator','Sensor ranges, bandwidths and digital low-pass filters, followed by attitude estimation.', ...
    {246,168}, [ ...
    card('GYROSCOPE',{'gyro.range','gyro.resolution_bits','gyro.BW','gyro.LPF_set'},1,1), ...
    card('ACCELEROMETER',{'accel.range','accel.resolution_bits','accel.BW','accel.LPF_set'},1,2), ...
    card('MAHONEY ATTITUDE ESTIMATOR',{'mahoney.Kp','mahoney.Ki'},2,[1 2])]);
add('Vehicle & mixer','Airframe geometry, thrust response and actuator mixing.', ...
    {284,240}, [ ...
    card('AIRFRAME',{'m','S','wing_type'},1,1), ...
    card('ACTUATORS & OUTPUT LIMIT',{'C11','C21','tau_wing','k_tau','max_pot'},1,2), ...
    card('BODY INERTIA',{'I'},2,1), ...
    card('MIXER',{'MMA'},2,2)]);
add('Aerodynamics','Choose the damping model, then set its reference motion, coefficients and areas.', ...
    {104,284,246}, [ ...
    card('DAMPING MODEL',{'use_time_constant_damping'},1,[1 2]), ...
    card('REFERENCE MOTION',{'v_ref','w_ref','p_ref','q_ref','r_ref'},2,1), ...
    card('RATE DECAY TIMES',{'tau_p','tau_q','tau_r'},2,2), ...
    card('DRAG COEFFICIENTS',{'CDx','CDy','CDz','CDw'},3,1), ...
    card('EFFECTIVE AREAS',{'AxFactor','AyFactor','AzFactor','AomegaFactor'},3,2)]);
add('State & command','Initial and target states use SI units. Angles are radians; z and w are positive down.', ...
    {468}, [card('INITIAL STATE',{'X0'},1,1),card('TARGET STATE',{'Xref'},1,2)]);
add('Simulation','Run duration, controller timing, repeatable noise and ambient conditions.', ...
    {208,170}, [ ...
    card('SIMULATION & TIMING',{'sim_fidelity','t_sim','fs'},1,1), ...
    card('SIMULATED NOISE',{'noise_true','seed'},1,2), ...
    card('ENVIRONMENT',{'g','rho'},2,[1 2])]);

    function add(name,description,heights,cards)
        pages(end+1)=struct('Name',name,'Description',description, ...
            'Heights',{heights},'Cards',cards);
    end
end

function c=card(title,keys,row,column,kind)
if nargin<5, kind='fields'; end
c=struct('Title',title,'Keys',{keys},'Row',row,'Column',column,'Kind',kind);
end
